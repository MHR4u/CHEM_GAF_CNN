"""
gaf_cnn_full_output.py
======================

Runs the trained GAF CNN (the model generated by gaf_cnn.py, i.e.
CNN_5classes__epo_4000_pat_1000_batch_16_tl.keras) on a test split and saves
EVERY output the CNN produces into complete files, instead of only printing
them to the screen.

Everything that gaf_cnn.py's test() prints is written out in full:
  * model architecture summary (what the CNN is made of)
  * the raw probability matrix for every single image (all classes, not truncated)
  * the predicted class of every image
  * the confusion matrix
  * the overall accuracy and the accuracy per class
  * the sklearn classification report
  * the list of misclassified images

For each split it creates, inside the output directory:
  <split>_full_output.txt        -> the complete text report (everything above)
  <split>_predictions.csv        -> per-image: true class, predicted class, all probabilities
  <split>_confusion_matrix.csv   -> confusion matrix as CSV
  <split>_classification_report.txt -> sklearn report
  <split>_summary.json           -> machine readable summary (accuracy, counts, model, params)
  <split>_confusion_matrix.png   -> confusion matrix heat map

Usage:
    python3 gaf_cnn_full_output.py \
        --model CNN_5classes__epo_4000_pat_1000_batch_16_tl.keras \
        --splits ../data/gafimages/shuffled/Test ../data/gafimages/concentrations_based/Test \
        --out_dir ../results
"""

import os
import sys
import json
import argparse

import matplotlib
matplotlib.use("Agg")  # no display needed, we save figures to files
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from sklearn.metrics import classification_report, confusion_matrix

# Reuse the exact architecture / helper of the original pipeline so the
# results are identical to running gaf_cnn.py itself.
from gaf_cnn import simple_cnn, evalAccuracy

IMG_HEIGHT, IMG_WIDTH = 224, 224

# Same order used by gaf_cnn.py (alphabetic order of the Train folders)
TARGET_NAMES = [
    "Benzochinone",
    "Catecolo",
    "Ferro-Ferri",
    "Idrochinone",
    "Idrochinone-Benzochinone",
]


def count_test_files(test_data_dir):
    """Same counting rule as gaf_cnn.py's get_nb_files (kept for report parity)."""
    import glob
    cnt = 0
    for r, dirs, files in os.walk(test_data_dir):
        for dr in dirs:
            cnt += len(glob.glob(os.path.join(r, dr + "/*")))
    return cnt


def load_model(model_path, n_classes):
    """Build the same CNN as gaf_cnn.py and load the trained weights into it."""
    model = simple_cnn(n_classes=n_classes)
    model.load_weights(model_path)
    return model


def run_split(model, split_dir, split_name, out_dir, model_path):
    """Evaluate one test split and write every generated output to files."""
    nb_test_samples = count_test_files(split_dir)

    test_datagen = ImageDataGenerator(rescale=1.0 / 255)
    test_generator = test_datagen.flow_from_directory(
        split_dir,
        target_size=(IMG_HEIGHT, IMG_WIDTH),
        color_mode="rgb",
        shuffle=False,
        class_mode="categorical",
        batch_size=1,
    )

    # file names in the exact order the generator feeds them (shuffle=False)
    file_names = [os.path.basename(f) for f in test_generator.filepaths]

    probabilities = model.predict(test_generator, nb_test_samples)
    true_classes = np.array(test_generator.classes)
    predicted_classes = np.argmax(probabilities, axis=1)

    cm = confusion_matrix(true_classes, predicted_classes)
    accuracy, accuracy_by_row = evalAccuracy(cm)
    report = classification_report(
        true_classes, predicted_classes, target_names=TARGET_NAMES, digits=4, zero_division=0
    )

    # ---------------------------------------------------------------- CSV files
    os.makedirs(out_dir, exist_ok=True)

    df = pd.DataFrame(
        {
            "file": file_names,
            "true_class": [TARGET_NAMES[i] for i in true_classes],
            "predicted_class": [TARGET_NAMES[i] for i in predicted_classes],
            "correct": [
                bool(t == p) for t, p in zip(true_classes, predicted_classes)
            ],
        }
    )
    for i, name in enumerate(TARGET_NAMES):
        df["prob_" + name] = probabilities[:, i]
    df["max_confidence"] = probabilities.max(axis=1)
    pred_csv = os.path.join(out_dir, f"{split_name}_predictions.csv")
    df.to_csv(pred_csv, index=False)

    cm_csv = os.path.join(out_dir, f"{split_name}_confusion_matrix.csv")
    pd.DataFrame(cm, index=TARGET_NAMES, columns=TARGET_NAMES).to_csv(cm_csv)

    report_txt = os.path.join(out_dir, f"{split_name}_classification_report.txt")
    with open(report_txt, "w") as f:
        f.write(f"CNN classification report - split: {split_name}\n")
        f.write(f"model: {os.path.basename(model_path)}\n")
        f.write("=" * 100 + "\n")
        f.write(report)

    # ------------------------------------------------------- summary + figure
    summary = {
        "split": split_name,
        "test_dir": os.path.abspath(split_dir),
        "model": os.path.abspath(model_path),
        "model_params": int(model.count_params()),
        "n_test_images": int(len(true_classes)),
        "n_test_images_reported_by_original_function": int(nb_test_samples),
        "n_classes": len(TARGET_NAMES),
        "class_names": TARGET_NAMES,
        "accuracy_percent": round(float(accuracy), 4),
        "accuracy_by_class_percent": {
            TARGET_NAMES[i]: round(float(accuracy_by_row[i]), 4) for i in range(len(TARGET_NAMES))
        },
        "n_correct": int((true_classes == predicted_classes).sum()),
        "n_wrong": int((true_classes != predicted_classes).sum()),
        "confusion_matrix": cm.tolist(),
    }
    summary_json = os.path.join(out_dir, f"{split_name}_summary.json")
    with open(summary_json, "w") as f:
        json.dump(summary, f, indent=2)

    png = os.path.join(out_dir, f"{split_name}_confusion_matrix.png")
    fig, ax = plt.subplots(figsize=(7, 6))
    im = ax.imshow(cm, cmap="Blues")
    ax.set_xticks(range(len(TARGET_NAMES)), TARGET_NAMES, rotation=45, ha="right")
    ax.set_yticks(range(len(TARGET_NAMES)), TARGET_NAMES)
    ax.set_xlabel("Predicted label")
    ax.set_ylabel("True label")
    ax.set_title(f"Confusion matrix - {split_name}\naccuracy = {accuracy:.2f}%")
    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            ax.text(j, i, str(cm[i, j]), ha="center", va="center",
                    color="white" if cm[i, j] > cm.max() / 2 else "black")
    fig.colorbar(im, ax=ax)
    fig.tight_layout()
    fig.savefig(png, dpi=130)
    plt.close(fig)

    # -------------------------------------------------- full text report file
    with open(os.path.join(out_dir, f"{split_name}_full_output.txt"), "w") as f:
        f.write("=" * 100 + "\n")
        f.write("FULL OUTPUT GENERATED BY THE CNN\n")
        f.write(f"model file         : {os.path.basename(model_path)}\n")
        f.write(f"model parameters   : {model.count_params():,}\n")
        f.write(f"test split         : {os.path.abspath(split_dir)}\n")
        f.write(f"test images        : {len(true_classes)}\n")
        f.write("classes            : " + ", ".join(TARGET_NAMES) + "\n")
        f.write("=" * 100 + "\n\n")

        f.write("--- MODEL ARCHITECTURE (model.summary()) ---\n\n")
        buf_lines = []
        model.summary(print_fn=lambda line: buf_lines.append(line))
        f.write("\n".join(buf_lines))
        f.write("\n\n")

        f.write("--- IMAGES FED TO THE CNN (order is preserved, shuffle=False) ---\n\n")
        for i, fn in enumerate(file_names):
            f.write(f"{i:4d}  {fn}\n")
        f.write("\n")

        f.write(f"--- PREDICTION OF {len(true_classes)} ROWS (raw probabilities, full precision) ---\n\n")
        with np.printoptions(precision=8, suppress=False, threshold=sys.maxsize, linewidth=200):
            f.write(str(probabilities))
            f.write("\n\n")

        f.write("--- TRUE CLASS INDEX OF EVERY ROW (test_generator.classes) ---\n\n")
        f.write(str(true_classes))
        f.write("\n\n")

        f.write("--- PREDICTED CLASS INDEX OF EVERY ROW (argmax of probabilities) ---\n\n")
        f.write(str(predicted_classes))
        f.write("\n\n")

        f.write("--- PER IMAGE RESULT ---\n\n")
        f.write(f"{'#':>4}  {'file':<45} {'true':<26} {'predicted':<26} {'confidence':>10} {'ok':>3}\n")
        for i, fn in enumerate(file_names):
            t, p = true_classes[i], predicted_classes[i]
            f.write(
                f"{i:4d}  {fn:<45} {TARGET_NAMES[t]:<26} {TARGET_NAMES[p]:<26} "
                f"{probabilities[i, p]:>10.6f} {'YES' if t == p else 'NO':>3}\n"
            )
        f.write("\n")

        f.write("--- CONFUSION MATRIX ---\n\n")
        f.write("(rows = true label, columns = predicted label, alphabetic class order)\n\n")
        f.write(pd.DataFrame(cm, index=TARGET_NAMES, columns=TARGET_NAMES).to_string())
        f.write("\n\n")

        f.write(f"Accuracy: {accuracy}\n\n")
        f.write("Accuracy by row (per class):\n")
        for i in range(len(accuracy_by_row)):
            f.write(f"\t{TARGET_NAMES[i]} => {accuracy_by_row[i]}\n")
        f.write("\n")

        f.write("--- CLASSIFICATION REPORT ---\n\n")
        f.write(report)
        f.write("\n")

        wrong = np.where(true_classes != predicted_classes)[0]
        f.write(f"--- MISCLASSIFIED IMAGES ({len(wrong)} of {len(true_classes)}) ---\n\n")
        if len(wrong) == 0:
            f.write("none - every test image was classified correctly\n")
        else:
            for i in wrong:
                f.write(
                    f"{file_names[i]}  true={TARGET_NAMES[true_classes[i]]} "
                    f"predicted={TARGET_NAMES[predicted_classes[i]]} "
                    f"(confidence {probabilities[i, predicted_classes[i]]:.6f})\n"
                )
        f.write("\nEnd of CNN output\n")

    return summary


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="CNN_5classes__epo_4000_pat_1000_batch_16_tl.keras")
    parser.add_argument(
        "--splits",
        nargs="+",
        default=["../data/gafimages/shuffled/Test", "../data/gafimages/concentrations_based/Test"],
    )
    parser.add_argument("--out_dir", default="../results")
    args = parser.parse_args()

    model = load_model(args.model, n_classes=len(TARGET_NAMES))
    print(f"Model loaded: {args.model} ({model.count_params():,} parameters)")

    all_summaries = []
    for split_dir in args.splits:
        split_name = split_dir.rstrip("/").split("/")[-2]  # 'shuffled' or 'concentrations_based'
        print("=" * 80)
        print(f"Running CNN on split '{split_name}': {split_dir}")
        print("=" * 80)
        summary = run_split(model, split_dir, split_name, args.out_dir, args.model)
        all_summaries.append(summary)
        print(json.dumps({k: v for k, v in summary.items() if k != "confusion_matrix"}, indent=2))

    combined = os.path.join(args.out_dir, "all_splits_summary.json")
    with open(combined, "w") as f:
        json.dump(all_summaries, f, indent=2)
    print(f"\nAll outputs written to: {os.path.abspath(args.out_dir)}")


if __name__ == "__main__":
    main()
